#!/usr/bin/env python3
import importlib.util
import re
import subprocess
import sys
from pathlib import Path

VARIANTS = Path(__file__).with_name("gen-variants.py")
WAYBAR = Path.home() / ".config" / "waybar" / "palette.css"
STATE = Path.home() / ".local" / "state" / "aurora"
ALACRITTY = STATE / "alacritty.toml"
HYPR = STATE / "hypr-palette.lua"
TMUX = STATE / "tmux.conf"
PILL_LEFT = "\ue0b6"
PILL_RIGHT = "\ue0b4"
DEFAULT_PALETTE = "purple"
TEXT = "#f3ecfb"


def palettes() -> dict:
    sys.dont_write_bytecode = True
    spec = importlib.util.spec_from_file_location("gen_variants", VARIANTS)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.PALETTES


def active_wallpaper() -> str:
    out = subprocess.run(["hyprctl", "hyprpaper", "listactive"], capture_output=True, text=True).stdout
    return next((line.split(": ", 1)[1] for line in out.splitlines() if "landscape" in line and ": " in line), "")


def channels(hex_color: str) -> tuple:
    return tuple(int(hex_color.lstrip("#")[i:i + 2], 16) for i in (0, 2, 4))


def rgba(hex_color: str, alpha: float) -> str:
    r, g, b = channels(hex_color)
    return f"rgba({r}, {g}, {b}, {alpha})"


def hypr_rgba(hex_color: str, alpha_hex: str) -> str:
    return f"rgba({hex_color.lstrip('#').lower()}{alpha_hex})"


def waybar_css(name: str, sky: list, ridges: list, glow: str) -> str:
    return "\n".join([
        f"/* generated by theme/aurora/palette.py for '{name}' */",
        f"@define-color glass {rgba(sky[1], 0.55)};",
        f"@define-color tooltip_bg {rgba(sky[0], 0.94)};",
        f"@define-color edge {rgba(ridges[0], 0.35)};",
        f"@define-color accent {glow};",
        f"@define-color accent_glow {rgba(glow, 0.9)};",
        f"@define-color hover {rgba(sky[3], 0.25)};",
        "",
    ])


def alacritty_toml(name: str, sky: list, ridges: list, glow: str) -> str:
    return "\n".join([
        f"# generated by theme/aurora/palette.py for '{name}'",
        "[colors.primary]",
        f"background = '{sky[0]}'",
        f"foreground = '{TEXT}'",
        "[colors.cursor]",
        f"text = '{sky[0]}'",
        f"cursor = '{glow}'",
        "[colors.vi_mode_cursor]",
        f"text = '{sky[0]}'",
        f"cursor = '{sky[4]}'",
        "[colors.selection]",
        f"text = '{sky[0]}'",
        f"background = '{glow}'",
        "[colors.normal]",
        f"black = '{sky[1]}'",
        "[colors.bright]",
        f"black = '{ridges[0]}'",
        "",
    ])


def hypr_lua(name: str, sky: list, floor: str, glow: str) -> str:
    return "\n".join([
        f"-- generated by theme/aurora/palette.py for '{name}'",
        "hl.config({",
        "    general = { col = {",
        f'        active_border = {{ colors = {{ "{hypr_rgba(glow, "ee")}", "{hypr_rgba(sky[4], "ee")}" }}, angle = 45 }},',
        '        inactive_border = "rgba(ffffff14)",',
        "    } },",
        f'    decoration = {{ shadow = {{ color = "{hypr_rgba(floor, "99")}" }} }},',
        "})",
        "",
    ])


def pill(text: str, fill: str, ink: str) -> str:
    return f"#[fg={fill},bg=default]{PILL_LEFT}#[fg={ink},bg={fill},bold]{text}#[fg={fill},bg=default,nobold]{PILL_RIGHT}"


def tmux_conf(name: str, sky: list, ridges: list, glow: str) -> str:
    dim = sky[4]
    return "\n".join([
        f"# generated by theme/aurora/palette.py for '{name}'",
        f'set -g status-style "bg=default,fg={dim}"',
        f'set -g status-left "{pill(" #S ", sky[2], TEXT)} "',
        f'set -g status-right "#[fg={dim}]%H:%M  {pill(" %d/%m ", sky[1], TEXT)}"',
        f'setw -g window-status-format "#[fg={dim}] #W "',
        f'setw -g window-status-current-format "{pill(" #W ", glow, sky[0])}"',
        'setw -g window-status-current-style "bg=default"',
        f'setw -g window-status-activity-style "bg=default,fg={glow},underscore"',
        f'set -g pane-border-style "fg={ridges[2]},bg=default"',
        f'set -g pane-active-border-style "fg={glow},bg=default"',
        f'set -g pane-border-format "#[fg={ridges[0]}] #P "',
        "set -g window-style 'bg=default'",
        "set -g window-active-style 'bg=default'",
        f'set -g message-style "bg={sky[1]},fg={TEXT},bold"',
        f'set -g message-command-style "bg={sky[2]},fg={TEXT},bold"',
        f'set -g mode-style "bg={glow},fg={sky[0]}"',
        f'set -g clock-mode-colour "{glow}"',
        "",
    ])


def reload_tmux() -> None:
    subprocess.run(["tmux", "source-file", str(TMUX)], capture_output=True)


def write_if_changed(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def main() -> None:
    wallpaper = sys.argv[1] if len(sys.argv) > 1 else active_wallpaper()
    match = re.match(r"([a-z]+)-\d+-", Path(wallpaper).name)
    table = palettes()
    name = match.group(1) if match and match.group(1) in table else DEFAULT_PALETTE
    sky, ridges, glow, floor, _led = table[name]
    write_if_changed(WAYBAR, waybar_css(name, sky, ridges, glow))
    write_if_changed(ALACRITTY, alacritty_toml(name, sky, ridges, glow))
    write_if_changed(HYPR, hypr_lua(name, sky, floor, glow))
    write_if_changed(TMUX, tmux_conf(name, sky, ridges, glow))
    reload_tmux()
    subprocess.run(["hyprctl", "eval", f"dofile('{HYPR}')"], capture_output=True)
    print(f"{wallpaper} -> {name}")


if __name__ == "__main__":
    main()
